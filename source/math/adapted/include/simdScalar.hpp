namespace vanguard::math::simd
{
    //////////////////////////////////////////////////////////////////////////
    Scalar::Scalar() : V(_mm_setzero_ps()) {}

    //////////////////////////////////////////////////////////////////////////
    Scalar::Scalar(const red::Float _f) : V(_mm_set1_ps(_f)) {}

    //////////////////////////////////////////////////////////////////////////
    Scalar::Scalar(const Scalar& _v) : V(_v.V) {}

    //////////////////////////////////////////////////////////////////////////
    Scalar::Scalar(const red::Float* _f) : V(_mm_load1_ps(_f)) {}

    //////////////////////////////////////////////////////////////////////////
    Scalar::Scalar(Quad _v) : V(_v) {}

    //////////////////////////////////////////////////////////////////////////
    Scalar::~Scalar() {}

    //////////////////////////////////////////////////////////////////////////
    Scalar& Scalar::operator=(const Scalar& _v)
    {
        V = _v.V;
        return *this;
    }

    //////////////////////////////////////////////////////////////////////////
    Scalar::operator float() const
    {
        return X;
    }

    //////////////////////////////////////////////////////////////////////////
    const red::Float* Scalar::AsFloat() const
    {
        return &X;
    }

    //////////////////////////////////////////////////////////////////////////
    void Scalar::Set(red::Float _f)
    {
        V = _mm_set1_ps(_f);
    }

    //////////////////////////////////////////////////////////////////////////
    void Scalar::Set(const Scalar& _v)
    {
        V = _v.V;
    }

    //////////////////////////////////////////////////////////////////////////
    void Scalar::Set(const red::Float* _f)
    {
        V = _mm_load1_ps(_f);
    }

    //////////////////////////////////////////////////////////////////////////
    void Scalar::SetZeros()
    {
        V = _mm_setzero_ps();
    }

    //////////////////////////////////////////////////////////////////////////
    void Scalar::SetOnes()
    {
        V = _mm_set1_ps(1.0f);
    }

    //////////////////////////////////////////////////////////////////////////
    Scalar& Scalar::Negate()
    {
        V = _mm_xor_ps(V, SIGN_MASK);
        return *this;
    }

    //////////////////////////////////////////////////////////////////////////
    Scalar Scalar::Negated() const
    {
        Quad negVal = _mm_xor_ps(V, SIGN_MASK);
        return Scalar(negVal);
    }

    //////////////////////////////////////////////////////////////////////////
    Scalar Scalar::Abs() const
    {
        Quad absVal = _mm_max_ps(_mm_sub_ps(_mm_setzero_ps(), V), V);
        return Scalar(absVal);
    }

    //////////////////////////////////////////////////////////////////////////
    red::Bool Scalar::IsZero() const
    {
        Scalar test(_mm_cmpeq_ps(_mm_setzero_ps(), V));
        return (test.Xi != 0);
    }

    //////////////////////////////////////////////////////////////////////////
    red::Bool Scalar::IsAlmostZero(const Quad _epsilon) const
    {
        Quad absVal = _mm_max_ps(_mm_sub_ps(_mm_setzero_ps(), V), V);
        Scalar test(_mm_cmpge_ps(_epsilon, absVal));
        return (test.Xi != 0);
    }
} // namespace vanguard::math::simd
