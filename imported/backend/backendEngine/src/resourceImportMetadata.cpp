ResourceImportMetadata::ResourceImportMetadata()
{
	std::memset(m_assetChecksum, 0, sizeof(MD5));
}


const FootIKOverrideData& ResourceImportMetadata::GetFootIkDataOverride() const
{
	RED_ASSERT( m_footIkOverrideDataIsValid );
	return m_footIkOverrideData;

}



void ResourceImportMetadata::SetIntermediateHost( const String& host )
{
	m_intermediateHost = host;
	m_intermediateHost.ToLower(); // make host name always lower case
}

void ResourceImportMetadata::SetIntermediatePath( const String& path )
{
	// Making the path into an AbsolutePath will sanitise it and put it into
	// a simplified and consistent format. It will ensure that we store an
	// actual full absolute path as required in the specification.
	SetIntermediatePath( red::AbsolutePath::CreateFilePath( path ) );
}

void ResourceImportMetadata::SetIntermediatePath( const red::AbsolutePath& path )
{
	m_intermediatePath = path.AsString();
}

void ResourceImportMetadata::SetIntermediateAuthor( const String& name )
{
	m_intermediateAuthor = name;
}

void ResourceImportMetadata::SetAssetHost( const String& host )
{
	m_assetHost = host;
	m_assetHost.ToLower(); // make host name always lower case
}

void ResourceImportMetadata::SetAssetPath( const String& path )
{
	// Making the path into an AbsolutePath will sanitise it and put it into
	// a simplified and consistent format. It will ensure that we store an
	// actual full absolute path as required in the specification.
	SetAssetPath( red::AbsolutePath::CreateFilePath( path ) );
}

void ResourceImportMetadata::SetAssetPath( const red::AbsolutePath& path )
{
	m_assetPath = path.AsString();
}

void ResourceImportMetadata::SetAssetVersionControlPath( const String& path )
{
	// Must adhere to the Depot syntax to specify files (although we fix \\ -> / )
	// "//depot/source/module/file.ext"
	RED_FATAL_ASSERT( path.BeginsWith( "//" ), "Perforce path must begin //" );

	RED_FATAL_ASSERT( !path.Contains( '@' ), "Perforce path should not contain @ revision specifier" );
	RED_FATAL_ASSERT( !path.Contains( '#' ), "Perforce path should not contain # revision specifier" );

	RED_FATAL_ASSERT( !path.Contains( "*" ), "Perforce path should not contain * wildcards" );
	RED_FATAL_ASSERT( !path.Contains( String( "..." ) ), "Path should not contain ... wildcards" );

	String fixedPath = path;
	fixedPath.ReplaceAll( '\\', '/' );

	m_assetVersionControlPath = fixedPath;
}

void ResourceImportMetadata::SetAssetVersionControlRevision( Uint32 revision )
{
	m_assetVersionControlRevision = revision;
}

void ResourceImportMetadata::SetAssetChecksum( const MD5& checksum )
{
	std::memcpy( m_assetChecksum, checksum, sizeof(MD5) );
}

void ResourceImportMetadata::SetFootIkDataOverride( const FootIKOverrideData& data )
{
	m_footIkOverrideDataIsValid = true;
	m_footIkOverrideData = data;
}
void ResourceImportMetadata::SetAutoGeneratedFootIkData( const FootIKOverrideData& data )
{
	RED_ASSERT( !m_footIkOverrideDataIsValid );
	if( !m_footIkOverrideDataIsValid )
	{
		m_footIkOverrideData = data;
	}
}
void ResourceImportMetadata::ClearFootIkOverrideData()
{
	m_footIkOverrideDataIsValid = false;
}

const THandle< ResourceImportOptions >& ResourceImportMetadata::GetImportOptions() const
{
	return m_importOptions;
}

void ResourceImportMetadata::SetImportOptions( const THandle< ResourceImportOptions >& options )
{
	m_importOptions = options;
}

